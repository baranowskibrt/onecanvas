def _discover_scannet(img_root):
    """Yield (scene_id, scene_root, color_files) for ScanNet scenes."""
    if not os.path.isdir(img_root):
        return
    for scene_id in sorted(os.listdir(img_root)):
        scene_root = os.path.join(img_root, scene_id)
        if not os.path.isdir(scene_root):
            continue
        color_path = os.path.join(scene_root, "color")
        if not os.path.isdir(color_path):
            continue
        color_files = sorted(Path(color_path).glob("*.jpg"))
        if not color_files:
            continue
        yield scene_id, scene_root, color_files


