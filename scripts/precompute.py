def _iter_scenes(cfg, args):
    """Yield (scene_id, scene_root, color_files) tuples for all phases.

    Honors --scenes / --scene_start / --scene_end / --shuffle / --split / cfg["splits"].
    `scene_root` is the directory where geometry/feature files live (already
    accounts for cfg["scene_subdir_fn"], so it points at iphone/ or dslr/ for
    ScanNet++).
    """
    if args.split is not None:
        roots = [cfg["root"].rstrip("/") + "/" + args.split + "/"]
    elif cfg.get("splits"):
        roots = [cfg["root"].rstrip("/") + "/" + s + "/" for s in cfg["splits"]]
    else:
        roots = [cfg["root"]]

    discover = cfg["discover_fn"]
    all_scenes: List[Tuple[str, str, List[Path]]] = []
    for root in roots:
        if not os.path.isdir(root):
            print(f"Skipping missing root: {root}")
            continue
        all_scenes.extend(discover(root))

    if args.shuffle:
        rng = random.Random(args.seed)
        rng.shuffle(all_scenes)

    if args.scene_start is not None or args.scene_end is not None:
        all_scenes = all_scenes[args.scene_start:args.scene_end]

    scenes_filter = set(args.scenes) if args.scenes else None
    for scene_id, scene_root, color_files in all_scenes:
        if scenes_filter and scene_id not in scenes_filter:
            continue
        yield scene_id, scene_root, color_files


