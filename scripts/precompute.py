def _crop_borders(img: Image.Image, ratio: float) -> Image.Image:
    """Remove ratio*size pixels from each side to strip lens-distortion borders."""
    if ratio <= 0:
        return img
    w, h = img.size
    cx = int(round(w * ratio))
    cy = int(round(h * ratio))
    return img.crop((cx, cy, w - cx, h - cy))


def uniform_sample(items, n):
    """Return n items sampled as uniformly as possible from items via linspace."""
    if n >= len(items):
        return list(items)
    indices = np.linspace(0, len(items) - 1, n, dtype=int)
    return [items[i] for i in indices]


def feature_subsample_indices(n_depth: int, n_feature: int) -> list[int]:
    """Indices in the depth-frame list that become feature frames.

    The feature frames are a uniform subsample of the depth frames chosen so
    the set is divisible into 16 / 32 / 48 by simple slicing.
    """
    return np.linspace(0, n_depth - 1, n_feature, dtype=int).tolist()


