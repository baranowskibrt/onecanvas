def _resolve_depth_filename(cfg, args, variant: str) -> str:
    """variant in {"nonaligned", "aligned"}."""
    depth_cfg = cfg["depth"]
    if variant == "aligned":
        return depth_cfg["target_aligned"]
    if args.no_metric:
        return depth_cfg["target_nonaligned_nometric"]
    return depth_cfg["target_nonaligned"]


def _resolve_features_filename(cfg, args, model_id: str) -> str:
    """Output filename for the features phase, with resolution suffix logic
    matching the original features_saving.py:88-100 verbatim.
    """
    feat_cfg = cfg["features"]
    is_qwen3_vl = "qwen3-vl" in model_id.lower() or "qwen3_vl" in model_id.lower()
    base = feat_cfg["output_qwen3_vl"] if is_qwen3_vl else feat_cfg["output_qwen3_5"]

    res = args.feature_resolution
    if res and res != "320x240":
        if "320x240" in base:
            base = base.replace("320x240", res)
        else:
            stem, ext = os.path.splitext(base)
            base = f"{stem}_{res}{ext}"
    return base


def _resolve_features_img_subdir(cfg, args) -> str:
    feat_cfg = cfg["features"]
    subdir = feat_cfg["img_subdir_default"]
    res = args.feature_resolution
    if res and res != "320x240":
        if "320x240" in subdir:
            subdir = subdir.replace("320x240", res)
        else:
            subdir = f"{subdir}_{res}"
    return subdir


