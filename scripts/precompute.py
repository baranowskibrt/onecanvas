def parse_args():
    parser = argparse.ArgumentParser(
        description="Unified scene precompute pipeline (depth + features + verify).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--dataset", required=True, choices=sorted(DATASET_CONFIGS.keys()))

    # Phase flags (positive selection — any subset).
    parser.add_argument("--nonaligned", action="store_true",
                        help="Generate predicted-pose DA3 geometry (default _metric.pt).")
    parser.add_argument("--aligned", action="store_true",
                        help="Generate GT-pose-aligned geometry (_metric_aligned.pt). "
                             "Reuses depths/intrinsics from the nonaligned file if present; "
                             "pass --nonaligned --aligned to generate both from scratch.")
    parser.add_argument("--features", action="store_true",
                        help="Extract Qwen visual features.")
    parser.add_argument("--verify", action="store_true",
                        help="Run consistency checks (read-only by default).")

    # Variant flags.
    parser.add_argument("--no_metric", action="store_true",
                        help="Use non-metric DA3-Large instead of DA3NESTED-GIANT-LARGE-1.1. "
                             "Files are written WITHOUT the _metric suffix; the dataloader "
                             "does NOT read these — manual loader change required.")
    parser.add_argument("--feature_resolution", default="320x240",
                        help="Image resolution subdir/suffix for features phase. "
                             "Default 320x240; depth phases always use native resolution.")
    parser.add_argument("--model", default="Qwen/Qwen3-VL-8B-Instruct",
                        help="HF model id for the features phase.")

    # Scene selection.
    parser.add_argument("--scenes", nargs="+", default=None)
    parser.add_argument("--scene_start", type=int, default=None)
    parser.add_argument("--scene_end", type=int, default=None)
    parser.add_argument("--shuffle", action="store_true")
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--split", default=None,
                        help="ArkitScenes Training|Validation override.")

    # Verify cleanup.
    parser.add_argument("--delete", action="store_true",
                        help="In --verify mode, delete stale/corrupt files for regeneration.")

    args = parser.parse_args()

    # Default phases: nonaligned + features (the original two-script sequence).
    if not (args.nonaligned or args.aligned or args.features or args.verify):
        args.nonaligned = True
        args.features = True

    return args


def _validate_args(args, cfg):
    if args.no_metric and args.aligned:
        raise SystemExit(
            "--no_metric and --aligned are mutually exclusive (aligned needs the "
            "metric DA3 model for depth conditioning)."
        )
    if args.delete and not args.verify:
        print("WARNING: --delete has no effect without --verify; ignoring.")

    # VRAM pre-flight: warn if requesting depth + features together on a small GPU.
    needs_da3 = args.nonaligned  # aligned reuses nonaligned and doesn't load DA3
    needs_qwen = args.features
    if needs_da3 and needs_qwen and torch.cuda.is_available():
        try:
            total = torch.cuda.get_device_properties(0).total_memory
            if total < SMALL_GPU_BYTES:
                print(
                    f"\nWARNING: requesting depth + features in one invocation on a "
                    f"{total / 1024**3:.1f} GB GPU may OOM. Recommended split:\n"
                    f"  python scripts/precompute.py --dataset {args.dataset} --nonaligned [--aligned]\n"
                    f"  python scripts/precompute.py --dataset {args.dataset} --features\n"
                )
        except Exception:
            pass


def main():
    args = parse_args()
    cfg = DATASET_CONFIGS[args.dataset]
    _validate_args(args, cfg)

    _install_signal_handlers()
    torch.set_grad_enabled(False)

    print(f"Dataset: {args.dataset}")
    print(f"Phases: " + " ".join(
        flag for flag, on in [
            ("nonaligned", args.nonaligned),
            ("aligned", args.aligned),
            ("features", args.features),
            ("verify", args.verify),
        ] if on
    ))

    # ---- Lazy model loads (before the per-scene loop) ---------------------
    # Aligned reuses nonaligned's depths/intrinsics, so it does NOT need DA3
    # by itself. Only --nonaligned triggers DA3 loading.
    da3_model = None
    if args.nonaligned:
        da3_model = load_da3_model(metric=not args.no_metric)

    feature_model = None
    feature_processor = None
    feature_merge_size = None
    if args.features:
        feature_model, feature_processor = load_feature_model(args.model)
        feature_merge_size = feature_model.model.visual.spatial_merge_size

    # ---- Per-scene loop ---------------------------------------------------
    summary: Dict[str, int] = {
        "n_scenes": 0,
        "verify_ok": 0,
        "verify_bad": 0,
        "verify_deleted": 0,
        "nonaligned_processed": 0,
        "nonaligned_skipped": 0,
        "nonaligned_errors": 0,
        "aligned_processed": 0,
        "aligned_skipped": 0,
        "aligned_errors": 0,
        "features_processed": 0,
        "features_skipped": 0,
        "features_missing_geometry": 0,
        "features_corrupt_geometry": 0,
        "features_no_output": 0,
        "features_errors": 0,
    }
    verify_report: List[str] = []

    for scene_id, scene_root, color_files in _iter_scenes(cfg, args):
        summary["n_scenes"] += 1
        print(f"\n=== {scene_id} ===")
        try:
            if args.verify:
                verify_scene(cfg, args, scene_id, scene_root, color_files,
                             summary, verify_report)
            if args.nonaligned:
                nonaligned_scene(cfg, args, scene_id, scene_root, color_files,
                                 da3_model, summary)
            if args.aligned:
                aligned_scene(cfg, args, scene_id, scene_root, color_files,
                              da3_model, summary)
            if args.features:
                features_scene(cfg, args, scene_id, scene_root, color_files,
                               feature_model, feature_processor, feature_merge_size,
                               summary)
        except KeyboardInterrupt:
            raise
        except Exception as e:
            print(f"  ERROR processing {scene_id}: {e}")
            # Continue to the next scene; per-phase errors are already counted.

    # ---- Cleanup models ---------------------------------------------------
    del da3_model, feature_model, feature_processor
    cleanup_gpu()

    # ---- Final summary ----------------------------------------------------
    print("\n" + "=" * 60)
    print(f"Precompute summary ({args.dataset})")
    print("=" * 60)
    print(f"  scenes seen:                 {summary['n_scenes']}")
    if args.verify:
        print(f"  verify ok:                   {summary['verify_ok']}")
        print(f"  verify bad:                  {summary['verify_bad']}")
        if args.delete:
            print(f"  verify deleted (files):      {summary['verify_deleted']}")
        # Also show breakdown by issue kind.
        issue_counts = {k: v for k, v in summary.items()
                        if k.startswith("verify_") and k not in
                        ("verify_ok", "verify_bad", "verify_deleted")}
        for k, v in sorted(issue_counts.items()):
            print(f"    {k:<28} {v}")
    if args.nonaligned:
        print(f"  nonaligned processed:        {summary['nonaligned_processed']}")
        print(f"  nonaligned skipped:          {summary['nonaligned_skipped']}")
        print(f"  nonaligned errors:           {summary['nonaligned_errors']}")
    if args.aligned:
        print(f"  aligned processed:           {summary['aligned_processed']}")
        print(f"  aligned skipped:             {summary['aligned_skipped']}")
        print(f"  aligned errors:              {summary['aligned_errors']}")
    if args.features:
        print(f"  features processed:          {summary['features_processed']}")
        print(f"  features skipped:            {summary['features_skipped']}")
        print(f"  features missing geometry:   {summary['features_missing_geometry']}")
        print(f"  features corrupt geometry:   {summary['features_corrupt_geometry']}")
        print(f"  features no output:          {summary['features_no_output']}")
        print(f"  features errors:             {summary['features_errors']}")
    print("=" * 60)


if __name__ == "__main__":
    main()
