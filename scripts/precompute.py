def nonaligned_scene(cfg, args, scene_id, scene_root, color_files, da3_model, summary):
    """Compute predicted-pose DA3 metric geometry for one scene.

    Verbatim port of the original depth_saving.py main loop, scoped to a
    single scene and using the global lock infrastructure.
    """
    target_file = _resolve_depth_filename(cfg, args, "nonaligned")
    target_path = os.path.join(scene_root, target_file)
    model_id = DA3_MODEL_NOMETRIC if args.no_metric else DA3_MODEL_METRIC

    # CRITICAL PIN: any filename carrying `_metric` MUST come from the nested
    # metric DA3 (DA3_MODEL_METRIC). The non-nested DA3-Large is NOT metric;
    # writing its output under a `_metric` name would silently corrupt every
    # downstream metric read.
    assert ("_metric" in target_file) == (model_id == DA3_MODEL_METRIC), (
        f"metric-suffix / model mismatch: {target_file} vs {model_id}"
    )

    # Cleanup stale files listed in cfg["depth"]["stale_files"].
    for stale in cfg["depth"]["stale_files"]:
        stale_path = os.path.join(scene_root, stale)
        if os.path.exists(stale_path):
            os.remove(stale_path)
            print(f"  removed stale file: {stale}")

    # Skip if already done. Use a size threshold to catch obviously truncated
    # files without paying the cost of deserializing the full pickle on every
    # scene (torch.load is slow across thousands of existing scenes).
    if os.path.exists(target_path):
        if os.path.getsize(target_path) > 4096:
            summary["nonaligned_skipped"] += 1
            return
        print(f"  suspiciously small nonaligned file for {scene_id}, regenerating...")
        os.remove(target_path)

    if not _acquire_lock(target_path):
        print(f"  skipping {scene_id}: another process holds the lock")
        summary["nonaligned_skipped"] += 1
        return

    try:
        max_depth = cfg["depth"]["max_depth_frames"]
        max_feat = cfg["depth"]["max_feature_frames"]
        depth_files = uniform_sample(list(color_files), max_depth)
        feat_indices = feature_subsample_indices(len(depth_files), max_feat)
        feature_stems = [depth_files[i].stem for i in feat_indices]
        stems = [p.stem for p in depth_files]
        image_paths = [str(p) for p in depth_files]

        print(f"  [nonaligned] {len(image_paths)} depth frames, "
              f"{len(feature_stems)} feature frames")

        pil_images = []
        for p in image_paths:
            img = Image.open(p).convert("RGB")
            img = _crop_borders(img, cfg["border_crop_ratio"])
            pil_images.append(img)

        proj_depths, proj_poses, intrinsics = _compute_da3_geometry(pil_images, da3_model)

        scene_data = {}
        for i, stem in enumerate(stems):
            scene_data[stem] = {
                "depth": proj_depths[i].cpu(),
                "pose": proj_poses[i].cpu(),
                "intrinsics": intrinsics[i].cpu(),
            }
        scene_data["__feature_stems__"] = feature_stems

        torch.save(scene_data, target_path)

        # Provenance sidecar (release-port addition; the .pt payload above is
        # unchanged from the pre-release producer, which wrote no sidecar).
        with open(target_path + ".json", "w") as fh:
            json.dump({
                "model_id": model_id,
                "dataset": args.dataset,
                "scene_id": scene_id,
                "n_depth_frames": len(stems),
                "n_feature_frames": len(feature_stems),
                "border_crop_ratio": cfg["border_crop_ratio"],
                "created_unix": time.time(),
            }, fh, indent=2)

        print(f"  [nonaligned] saved -> {target_path}")
        summary["nonaligned_processed"] += 1
    except Exception:
        summary["nonaligned_errors"] += 1
        traceback.print_exc()
        raise
    finally:
        _release_lock(target_path)


