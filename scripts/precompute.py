def aligned_scene(cfg, args, scene_id, scene_root, color_files, da3_model, summary):
    """Build _aligned.pt by replacing poses in an existing _metric.pt with GT poses.

    Recipe (verified empirically against existing files):
      ScanNet:           pose_aligned[stem] = axisAlignment @ pose/<stem>.txt
      ScanNet++ iphone:  pose_aligned[stem] = pose_intrinsic_imu.json[stem]['pose']
      ScanNet++ dslr:    gravity-aligned + recentered from nerfstudio transforms
      ARKitScenes:       lowres_wide.traj nearest-ts match, y-up -> z-up via Rx(+90°)

    Depths, intrinsics, and __feature_stems__ are inherited from the existing
    nonaligned _metric.pt (verified bytewise identical between variants).
    """
    aligned_file = cfg["depth"]["target_aligned"]
    aligned_path = os.path.join(scene_root, aligned_file)
    nonaligned_file = cfg["depth"]["target_nonaligned"]
    nonaligned_path = os.path.join(scene_root, nonaligned_file)

    # Skip if already done.
    if os.path.exists(aligned_path):
        if os.path.getsize(aligned_path) > 4096:
            summary["aligned_skipped"] += 1
            return
        print(f"  suspiciously small aligned file for {scene_id}, regenerating...")
        os.remove(aligned_path)

    if not os.path.exists(nonaligned_path):
        print(f"  skipping {scene_id}: aligned requires existing {nonaligned_file} "
              f"(pass --nonaligned --aligned together)")
        summary["aligned_skipped"] += 1
        return

    if not _acquire_lock(aligned_path):
        print(f"  skipping {scene_id}: another process holds the aligned lock")
        summary["aligned_skipped"] += 1
        return

    try:
        nonaligned_data = torch.load(
            nonaligned_path, map_location="cpu", weights_only=False
        )
        gt_poses = cfg["gt_pose_loader"](scene_root, scene_id)

        existing_stems = [k for k in nonaligned_data.keys() if not k.startswith("__")]
        kept_stems = [s for s in existing_stems if s in gt_poses]
        n_dropped = len(existing_stems) - len(kept_stems)
        if n_dropped > 0:
            print(f"  [aligned] dropped {n_dropped}/{len(existing_stems)} frames "
                  f"missing GT poses")
        if n_dropped > len(existing_stems) * 0.5:
            raise RuntimeError(
                f"More than half the frames ({n_dropped}/{len(existing_stems)}) "
                f"have no GT pose; refusing to write a sparse aligned file."
            )

        scene_data = {}
        for stem in kept_stems:
            scene_data[stem] = {
                "depth": nonaligned_data[stem]["depth"],
                "pose": gt_poses[stem].cpu(),
                "intrinsics": nonaligned_data[stem]["intrinsics"],
            }

        # Inherit feature_stems but drop any that no longer have GT poses.
        feat_stems = nonaligned_data.get("__feature_stems__", [])
        feat_stems = [s for s in feat_stems if s in scene_data]
        scene_data["__feature_stems__"] = feat_stems

        torch.save(scene_data, aligned_path)
        print(f"  [aligned] saved {len(kept_stems)} frames -> {aligned_path}")
        summary["aligned_processed"] += 1
    except Exception:
        summary["aligned_errors"] += 1
        traceback.print_exc()
        raise
    finally:
        _release_lock(aligned_path)


