def get_batch_features(image_paths, border_crop_ratio, model, processor, merge_size):
    """Verbatim port of the original features_saving.py:161-194.

    model_adapters/qwen3_vl/model.py's decode-path feature reshaping mirrors
    the block below (the comment there cites scripts/precompute.py by line;
    the block starts at the `with torch.no_grad():` here).
    """
    images = [_crop_borders(Image.open(p).convert("RGB"), border_crop_ratio) for p in image_paths]
    inputs = processor(images=images, text=[""] * len(images), return_tensors="pt").to(model.device)

    with torch.no_grad():
        # No return_dict: 4.57.x's get_image_features does not accept it.
        # split_image_features normalizes the 4.57 tuple and the 5.x dataclass.
        image_outputs = model.model.get_image_features(
            inputs.pixel_values,
            inputs.image_grid_thw,
        )
        image_embeds_per_img, deepstack_features = split_image_features(image_outputs)

        h_feat = inputs.image_grid_thw[:, 1] // merge_size
        w_feat = inputs.image_grid_thw[:, 2] // merge_size
        tokens_per_img = (h_feat * w_feat).tolist()

        batch_results = []
        for i in range(len(image_paths)):
            h_i, w_i = int(h_feat[i]), int(w_feat[i])
            base_feat = image_embeds_per_img[i].view(h_i, w_i, -1).cpu()
            layers = [base_feat]

            if deepstack_features is not None:
                for layer_tensor in deepstack_features:
                    chunks = torch.split(layer_tensor, tokens_per_img, dim=0)
                    layers.append(chunks[i].view(h_i, w_i, -1).cpu())

            batch_results.append(torch.stack(layers, dim=0))

        return batch_results


def features_scene(cfg, args, scene_id, scene_root, color_files,
                   model, processor, merge_size, summary):
    """Extract Qwen visual features for one scene.

    Reads __feature_stems__ from whichever depth .pt is appropriate for the
    same-invocation phase flags. The feature file is variant-agnostic — both
    nonaligned and aligned share the same __feature_stems__ list.
    """
    output_file = _resolve_features_filename(cfg, args, args.model)
    output_path = os.path.join(scene_root, output_file)
    img_subdir = _resolve_features_img_subdir(cfg, args)
    img_ext = cfg["features"]["img_ext"]

    # Pick the geometry file to read __feature_stems__ from. Prefer whichever
    # variant the user is generating in the same invocation; fall back to
    # nonaligned, then aligned, then bail.
    candidates = []
    if args.aligned:
        candidates.append(cfg["depth"]["target_aligned"])
    if args.nonaligned or not args.aligned:
        candidates.append(cfg["depth"]["target_nonaligned"])
    candidates.append(cfg["depth"]["target_aligned"])
    if args.no_metric:
        candidates.append(cfg["depth"]["target_nonaligned_nometric"])
    seen = set()
    candidates = [c for c in candidates if c and not (c in seen or seen.add(c))]

    geometry_path = None
    for fn in candidates:
        p = os.path.join(scene_root, fn)
        if os.path.exists(p):
            geometry_path = p
            break

    if geometry_path is None:
        print(f"  [features] skipping {scene_id}: no geometry file found "
              f"(tried {candidates})")
        summary["features_missing_geometry"] += 1
        return

    if os.path.exists(output_path):
        summary["features_skipped"] += 1
        return

    if not _acquire_lock(output_path):
        print(f"  skipping {scene_id}: another process holds the features lock")
        summary["features_skipped"] += 1
        return

    try:
        try:
            geometry_data = torch.load(geometry_path, map_location="cpu", weights_only=False)
        except Exception as e:
            print(f"  [features] skipping {scene_id}: corrupt geometry ({e})")
            summary["features_corrupt_geometry"] += 1
            return

        valid_stems = (
            geometry_data["__feature_stems__"]
            if "__feature_stems__" in geometry_data
            else [k for k in geometry_data.keys() if not k.startswith("__")]
        )
        del geometry_data

        scene_features: Dict[str, torch.Tensor] = {}
        img_dir = os.path.join(scene_root, img_subdir)

        BATCH_SIZE = 50
        for i in range(0, len(valid_stems), BATCH_SIZE):
            batch_stems = valid_stems[i:i + BATCH_SIZE]
            batch_paths = [os.path.join(img_dir, f"{s}{img_ext}") for s in batch_stems]
            existing = [(idx, p) for idx, p in enumerate(batch_paths) if os.path.exists(p)]
            if not existing:
                continue
            proc_paths = [p for _, p in existing]
            proc_stems = [batch_stems[idx] for idx, _ in existing]
            features = get_batch_features(
                proc_paths, cfg["border_crop_ratio"], model, processor, merge_size,
            )
            for stem, feat in zip(proc_stems, features):
                scene_features[stem] = feat
            print(f"  [features] {scene_id}: {i + len(proc_stems)}/{len(valid_stems)}")

        if not scene_features:
            print(f"  [features] WARNING: no features produced for {scene_id} "
                  f"(check {img_dir}/ exists and contains {img_ext} files)")
            summary["features_no_output"] += 1
            return

        # Atomic write via temp + rename.
        temp_path = output_path + ".tmp"
        try:
            torch.save(scene_features, temp_path)
            torch.load(temp_path, map_location="cpu", mmap=True, weights_only=False)
            os.replace(temp_path, output_path)
            print(f"  [features] saved {len(scene_features)} frames -> {output_path}")
            summary["features_processed"] += 1
        except Exception:
            if os.path.exists(temp_path):
                os.remove(temp_path)
            raise
    except Exception:
        summary["features_errors"] += 1
        traceback.print_exc()
        raise
    finally:
        _release_lock(output_path)


