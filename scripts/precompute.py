def verify_scene(cfg, args, scene_id, scene_root, color_files, summary, report_lines):
    """Run the full battery of consistency checks for one scene.

    Builds a per-scene status dict and appends a human-readable line to
    report_lines. With --delete, removes files that need regeneration.
    """
    issues: List[str] = []
    files_to_delete: List[str] = []

    # ---- A. Image-source consistency -------------------------------------
    n_color_native = len(color_files)
    color_subdir_path = (
        Path(cfg["root"]) / scene_id / cfg["verify_color_subdir"]
        if not cfg.get("scene_subdir_fn")
        else Path(scene_root).parent / cfg["verify_color_subdir"]
    )
    # Note: scene_root for ScanNet++ is .../<scene>/iphone, so its parent is
    # .../<scene>; verify_color_subdir is "iphone/rgb" which when joined to
    # parent gives .../<scene>/iphone/rgb. The above branch handles that.
    # The simplest robust resolution: derive from the parent of color_files[0].
    color_dir = color_files[0].parent if color_files else None

    parent_for_resized = (
        Path(scene_root).parent if cfg.get("scene_subdir_fn") else Path(scene_root)
    )
    for resized_subdir in cfg.get("resized_subdirs", []):
        # resized_subdir may be "iphone/rgb_320x240" — that's relative to scene
        # parent for ScanNet++, or relative to scene_root for ScanNet/ArkitScenes.
        resized_path = parent_for_resized / resized_subdir
        if resized_path.exists():
            n_resized = sum(1 for _ in resized_path.iterdir() if _.is_file())
            if n_resized != n_color_native:
                issues.append(
                    f"mismatched_resize:{resized_subdir}({n_resized}/{n_color_native})"
                )

    # ---- B/C. Depth file checks ------------------------------------------
    expected_stems = set(p.stem for p in uniform_sample(list(color_files),
                                                         cfg["depth"]["max_depth_frames"]))
    depth_status = {}
    depth_data_per_variant: Dict[str, Optional[dict]] = {}

    variants = [
        ("nonaligned", cfg["depth"]["target_nonaligned"]),
        ("aligned", cfg["depth"]["target_aligned"]),
    ]
    for variant, fname in variants:
        path = os.path.join(scene_root, fname)
        if not os.path.exists(path):
            depth_status[variant] = "missing"
            depth_data_per_variant[variant] = None
            continue
        try:
            size = os.path.getsize(path)
        except OSError:
            size = 0
        if size == 0:
            issues.append(f"corrupt_depth_{variant}:zero_byte")
            depth_status[variant] = "corrupt"
            files_to_delete.append(path)
            depth_data_per_variant[variant] = None
            continue
        try:
            data = torch.load(path, map_location="cpu", mmap=True, weights_only=False)
        except Exception as e:
            issues.append(f"corrupt_depth_{variant}:{type(e).__name__}")
            depth_status[variant] = "corrupt"
            files_to_delete.append(path)
            depth_data_per_variant[variant] = None
            continue

        depth_data_per_variant[variant] = data

        if "__feature_stems__" not in data:
            issues.append(f"legacy_depth_{variant}:no_feature_stems")
            depth_status[variant] = "legacy"
            files_to_delete.append(path)
            continue

        actual_stems = set(k for k in data.keys() if not k.startswith("__"))
        if actual_stems != expected_stems:
            n_overlap = len(actual_stems & expected_stems)
            issues.append(
                f"stale_depth_{variant}:n_actual={len(actual_stems)},"
                f"n_expected={len(expected_stems)},n_overlap={n_overlap}"
            )
            depth_status[variant] = "stale"
            files_to_delete.append(path)
            continue

        # Spot-check structure on a few frames.
        sample_keys = random.sample(list(actual_stems), min(5, len(actual_stems)))
        bad_struct = False
        for k in sample_keys:
            d = data[k]["depth"]
            p = data[k]["pose"]
            ki = data[k]["intrinsics"]
            if d.dim() != 2 or d.dtype != torch.uint16 or d.numel() == 0:
                bad_struct = True
                break
            if p.shape != (4, 4) or not torch.isfinite(p).all():
                bad_struct = True
                break
            if ki.shape != (4,) or not torch.isfinite(ki).all():
                bad_struct = True
                break
        if bad_struct:
            issues.append(f"corrupt_depth_{variant}:bad_frame_struct")
            depth_status[variant] = "corrupt"
            files_to_delete.append(path)
            continue

        depth_status[variant] = "ok"

    # Cross-variant consistency
    nd = depth_data_per_variant.get("nonaligned")
    ad = depth_data_per_variant.get("aligned")
    if nd is not None and ad is not None:
        nd_stems = nd.get("__feature_stems__")
        ad_stems = ad.get("__feature_stems__")
        if nd_stems != ad_stems:
            issues.append("cross_variant_stale:feature_stems_diverge")
            # Mark the older one for deletion.
            np_path = os.path.join(scene_root, cfg["depth"]["target_nonaligned"])
            ap_path = os.path.join(scene_root, cfg["depth"]["target_aligned"])
            try:
                older = np_path if os.path.getmtime(np_path) < os.path.getmtime(ap_path) else ap_path
                files_to_delete.append(older)
            except OSError:
                pass

    # ---- D. Feature file checks ------------------------------------------
    feat_cfg = cfg["features"]
    expected_feature_stems = None
    for variant_data in depth_data_per_variant.values():
        if variant_data is not None and "__feature_stems__" in variant_data:
            expected_feature_stems = variant_data["__feature_stems__"]
            break

    # Only check feature files that match the current "balanced_64" convention.
    # Legacy "aggregated" files use a different stem set and are intentionally
    # ignored here — they predate the balanced subsample contract.
    feature_files: List[Tuple[str, str]] = [
        ("qwen3_vl", feat_cfg["output_qwen3_vl"]),
        ("qwen3_5", feat_cfg["output_qwen3_5"]),
    ]
    # Also check resolution-variant siblings (e.g. _640x480.pt) of the current
    # balanced_64 files.
    for path_obj in Path(scene_root).glob("qwen*_features_balanced_64*.pt"):
        name = path_obj.name
        if not any(name == f for _, f in feature_files):
            kind = "qwen3_vl" if "qwen3_vl" in name else "qwen3_5"
            feature_files.append((kind, name))

    for kind, fname in feature_files:
        path = os.path.join(scene_root, fname)
        if not os.path.exists(path):
            continue  # missing features is not an error — user may not have generated them
        try:
            size = os.path.getsize(path)
        except OSError:
            size = 0
        if size == 0:
            issues.append(f"corrupt_features:{fname}:zero_byte")
            files_to_delete.append(path)
            continue
        try:
            data = torch.load(path, map_location="cpu", mmap=True, weights_only=False)
        except Exception as e:
            issues.append(f"corrupt_features:{fname}:{type(e).__name__}")
            files_to_delete.append(path)
            continue
        actual_keys = set(data.keys())
        if expected_feature_stems is not None:
            expected_set = set(expected_feature_stems)
            if actual_keys != expected_set:
                missing = len(expected_set - actual_keys)
                extra = len(actual_keys - expected_set)
                issues.append(
                    f"stale_features:{fname}:missing={missing},extra={extra}"
                )
                files_to_delete.append(path)
                continue

        # Spot-check shape on 3 random frames.
        sample = random.sample(list(actual_keys), min(3, len(actual_keys)))
        expected_layers = _expected_layer_count(fname)
        bad = False
        for k in sample:
            t = data[k]
            if t.dim() != 4 or t.shape[0] != expected_layers:
                bad = True
                break
        if bad:
            issues.append(f"corrupt_features:{fname}:bad_shape")
            files_to_delete.append(path)

    # ---- Build report line -----------------------------------------------
    if not issues:
        status = "OK"
        summary["verify_ok"] += 1
    else:
        status = "BAD"
        summary["verify_bad"] += 1
        for tag in issues:
            kind = tag.split(":", 1)[0]
            summary[f"verify_{kind}"] = summary.get(f"verify_{kind}", 0) + 1

    line = f"[{status}] {scene_id}: " + (", ".join(issues) if issues else "all checks passed")
    print(f"  {line}")
    report_lines.append(line)

    # ---- --delete repair --------------------------------------------------
    if args.delete and files_to_delete:
        # Deduplicate paths.
        files_to_delete = list(dict.fromkeys(files_to_delete))
        # Add dependent feature files for any deleted depth file.
        deleted_depth = [p for p in files_to_delete if "da3_geometry" in os.path.basename(p)]
        if deleted_depth:
            for kind, fname in feature_files:
                fpath = os.path.join(scene_root, fname)
                if os.path.exists(fpath):
                    files_to_delete.append(fpath)
        files_to_delete = list(dict.fromkeys(files_to_delete))

        for path in files_to_delete:
            try:
                if os.path.exists(path):
                    os.remove(path)
                    print(f"    deleted: {os.path.basename(path)}")
                    summary["verify_deleted"] += 1
            except OSError as e:
                print(f"    FAILED to delete {path}: {e}")


