_ACTIVE_LOCKS: set[str] = set()


def _release_all_locks():
    """Unlink every lock currently held by this process. Safe to call twice."""
    for path in list(_ACTIVE_LOCKS):
        try:
            if os.path.exists(path):
                os.remove(path)
        except OSError:
            pass
        _ACTIVE_LOCKS.discard(path)


def _signal_handler(signum, frame):
    _release_all_locks()
    # Restore default handler and re-raise so the process actually exits.
    signal.signal(signum, signal.SIG_DFL)
    os.kill(os.getpid(), signum)


def _install_signal_handlers():
    atexit.register(_release_all_locks)
    signal.signal(signal.SIGINT, _signal_handler)
    signal.signal(signal.SIGTERM, _signal_handler)


def _acquire_lock(target_path: str) -> bool:
    """Try to acquire a `<target>.inprogress` lockfile.

    Returns True on success, False if another process holds it. Reclaims the
    lock if it is older than STALE_LOCK_AGE_SECONDS (orphaned writer).
    """
    lock_path = target_path + ".inprogress"

    # Reclaim a stale lock from a dead writer.
    if os.path.exists(lock_path):
        try:
            age = time.time() - os.path.getmtime(lock_path)
        except OSError:
            age = 0
        if age > STALE_LOCK_AGE_SECONDS:
            print(f"  reclaiming stale lock ({age/60:.1f} min old): {lock_path}")
            try:
                os.remove(lock_path)
            except OSError:
                pass

    try:
        # O_EXCL atomic create — fails if another process won the race.
        open(lock_path, "x").close()
    except FileExistsError:
        return False

    _ACTIVE_LOCKS.add(lock_path)
    return True


def _release_lock(target_path: str):
    lock_path = target_path + ".inprogress"
    try:
        if os.path.exists(lock_path):
            os.remove(lock_path)
    except OSError:
        pass
    _ACTIVE_LOCKS.discard(lock_path)


