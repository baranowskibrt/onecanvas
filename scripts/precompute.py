def load_feature_model(model_id: str):
    is_qwen3_vl = "qwen3-vl" in model_id.lower() or "qwen3_vl" in model_id.lower()
    print(f"Loading {model_id} ({'Qwen3-VL' if is_qwen3_vl else 'Qwen3.5'})...")
    if is_qwen3_vl:
        from transformers import Qwen3VLForConditionalGeneration
        model = Qwen3VLForConditionalGeneration.from_pretrained(
            model_id, torch_dtype=torch.bfloat16, device_map="auto",
        )
    else:
        from transformers import Qwen3_5ForConditionalGeneration
        model = Qwen3_5ForConditionalGeneration.from_pretrained(
            model_id, torch_dtype=torch.bfloat16, device_map="auto",
        )
    model.eval()
    from transformers import AutoProcessor
    processor = AutoProcessor.from_pretrained(model_id)
    # Disable processor-side resizing — features must be extracted at the
    # native image resolution.
    processor.image_processor.size["longest_edge"] = 67108864
    processor.image_processor.size["shortest_edge"] = 65536
    return model, processor


