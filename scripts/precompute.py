"""Unified precompute pipeline for scene preprocessing.

One CLI that runs any subset of:

  --nonaligned   Predicted-pose DA3 geometry  (da3_geometry_*_metric.pt)
  --aligned      GT-pose-aligned DA3 geometry (da3_geometry_*_metric_aligned.pt)
                 — uses GT poses; depths/intrinsics inherited from nonaligned
                   if it exists, otherwise nonaligned is generated first.
  --features     Qwen visual features         (qwen3_vl_features_balanced_64*.pt)
  --verify       Comprehensive consistency check; --delete to clean stale files

The loop is per-scene: every requested phase finishes for one scene before
moving to the next, so a parallel training run never sees a half-processed
scene.

Who consumes each output family (training/onecanvas/data/data_processor_3d.py):

  da3_geometry_balanced_256[_crop003]_metric.pt
      The default QA-path geometry: `_geometry_candidates(wants_aligned=False)`
      primary list (crop003 name for ScanNet, plain name for ScanNet++ /
      ARKitScenes). Also the last-ditch fallback for every predicted-geometry
      eval arm, and the pose source for the DA3_FALLBACK_SCENES below.
  da3_geometry_balanced_256[_crop003]_metric_aligned.pt
      The grounding path: `_geometry_candidates(wants_aligned=True)`.
      GT poses, DA3 depths/intrinsics.
  qwen3_vl_features_balanced_64*.pt
      NOT read by any loader path in this release. The QA dataloader returns raw
      pixel_values and the vision tower runs live inside forward() (the
      "PRE-PATH-A" block in model_adapters/qwen3_vl/model.py), so --features
      writes files nothing consumes. Do not spend GPU hours on it expecting an
      eval or a training run to need them; neither does.
  da3_geometry_balanced_256[_crop003].pt (--no_metric)
      NOT read by any loader path; manual loader change required.

Seven ScanNet++ iPhone scenes REQUIRE the nonaligned _metric.pt even on the
GT-pose path (`--use_gt_all True`): their ARKit GT pose tracks diverged during
capture (worst: 189 km trajectory span), so the loader forces the DA3-predicted
poses for them (DA3_FALLBACK_SCENES in data_processor_3d.py: 7dab70c8c8,
d755b3d9d8, 120acffd90, cc0aa81452, 46001f434d, ab4f373966, 02a980c994; the
last has no iPhone RGB extracted and is dropped rather than rescued). See
docs/bad_scenes.md.

GPU requirement: --nonaligned loads the DA3 nested-giant model and --features
loads a Qwen3-VL 8B tower; both need a CUDA GPU. Requesting depth + features
in one invocation on a GPU under 40 GB may OOM (a warning suggests the split).
--aligned alone and --verify are CPU-only.

Metric-model pin: any output whose filename carries `_metric` comes from the
DA3 model id `depth-anything/DA3NESTED-GIANT-LARGE-1.1` (DA3_MODEL_METRIC).
The non-nested DA3-Large is NOT metric; its output is only ever written under
the suffix-free `--no_metric` names, and an assert enforces the pairing.

Release-port addition: each nonaligned geometry write now also drops a
provenance sidecar `<output>.pt.json` recording model_id (plus frame counts
and crop ratio). The pre-release producer wrote no sidecar; the .pt payload
itself is unchanged.

Example commands:

  python scripts/precompute.py --dataset scannet --nonaligned --aligned --features
  python scripts/precompute.py --dataset scannetpp --nonaligned --aligned --features
  python scripts/precompute.py --dataset arkitscenes --nonaligned --features --split Training

Dataset roots resolve through onecanvas.data (ONECANVAS_DATA_ROOT env var,
else a `datasets/` directory sitting next to the repo root).

Geometry filenames this script CAN produce, of the loader's candidate set:
  da3_geometry_balanced_256_crop003_metric.pt          (scannet, --nonaligned)
  da3_geometry_balanced_256_metric.pt                  (scannetpp / scannetpp_dslr / arkitscenes, --nonaligned)
  da3_geometry_balanced_256_crop003_metric_aligned.pt  (scannet, --aligned)
  da3_geometry_balanced_256_metric_aligned.pt          (scannetpp / scannetpp_dslr / arkitscenes, --aligned)
Filenames in `_geometry_candidates` this script CANNOT produce — the
predicted-geometry eval arms, generated by separate tools
(agentic-onecanvas predgeo / dvlt_da3anchor / predgeo_scale_calibrate
pipelines), listed here so nobody hunts for a flag that doesn't exist:
  {da3,mapanything,dvlt}_geometry_eval32_crop003_metric.pt
  {da3,mapanything,dvlt}_geometry_eval32_metric.pt
  {da3,mapanything,dvlt}_geometry_spbench_crop003_metric.pt
  {da3,dvlt}_geometry_eval32ctx256_crop003_metric.pt
  {da3,dvlt}_geometry_eval32ctx256_metric.pt
  {da3,dvlt}_geometry_spbenchctx256_crop003_metric.pt
  dvlt_geometry_eval32ctx256_upright_hires_metric.pt
  dvlt_geometry_eval32ctx256_hires_metric.pt
  {da3,dvlt}_geometry_eval32ctx_upright_hires_metric.pt
  {da3,dvlt}_geometry_eval32ctx_hires_metric.pt
  {da3,dvlt}_geometry_eval32_hires_metric.pt
  {da3,dvlt}_geometry_eval32ctx_hires_crop003_metric.pt
  {da3,dvlt}_geometry_spbenchctx_hires_crop003_metric.pt
  da3_geometry_eval32ctx_hires_{scalecal,scaleoracle}_crop003_metric.pt
  da3_geometry_spbenchctx_hires_{scalecal,scaleoracle}_crop003_metric.pt
  da3_geometry_eval32_hires32_crop003_metric.pt
  da3_geometry_eval32_upright_hires_metric.pt
"""

