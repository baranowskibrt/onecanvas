# All dataset trees referenced below live under a single root directory.
# Resolution order:
#   1. ONECANVAS_DATA_ROOT env var (explicit override, always wins).
#   2. A `datasets/` directory sitting next to the repo root, derived from this
#      file's own location (no hardcoded absolute path). This is the common
#      checkout layout (`<parent>/onecanvas`, `<parent>/datasets`) and means
#      launches via run-on-job / submit-job / eval don't have to remember to
#      export the var. Guarded on the directory actually existing so a
#      collaborator with a different layout still gets the explicit error below
#      rather than silently loading the wrong filesystem tree.
_DATA_ROOT = os.environ.get("ONECANVAS_DATA_ROOT")
