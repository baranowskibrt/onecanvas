    _repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
    _sibling_datasets = os.path.join(os.path.dirname(_repo_root), "datasets")
    if os.path.isdir(_sibling_datasets):
        _DATA_ROOT = _sibling_datasets
