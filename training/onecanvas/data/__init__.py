def parse_sampling_rate(dataset_name):
    match = re.search(r"%(\d+)$", dataset_name)
    if match:
        return int(match.group(1)) / 100.0
    return 1.0


def parse_dataset_weight(dataset_name):
    """Parse @N suffix → float weight (e.g. @7.8, @0.74). Returns None if absent."""
    match = re.search(r"@([\d.]+)$", dataset_name)
    return float(match.group(1)) if match else None


def data_list(dataset_names):
    config_list = []
    for dataset_name in dataset_names:
        weight = parse_dataset_weight(dataset_name)
        sampling_rate = parse_sampling_rate(dataset_name) if weight is None else 1.0
        clean_name = re.sub(r"[@%][\d.]+$", "", dataset_name)
        if clean_name not in data_dict:
            raise ValueError(f"do not find {clean_name}")
        config = data_dict[clean_name].copy()
        if weight is not None:
            config["dataset_weight"] = weight
        else:
            config["sampling_rate"] = sampling_rate
        config_list.append(config)
    return config_list


